package org.firstinspires.ftc.teamcode.FtcBiobuzz.util.math;

public class Vector2d {
    double x;
    double y;

    public Vector2d(double x, double y){
        this.x = x;
        this.y = y;
    }


    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}
